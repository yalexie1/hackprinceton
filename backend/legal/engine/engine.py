"""Drafting engine (L1): template loading, placeholder resolver, visible blanks, notice.

Resolution order for `{{name}}`: (1) a value in DocumentRequest.fields, (2) a derived value
from a binding, (3) verbatim statutory text for `stat_` names, (4) empty if the template
marks it optional, else (5) a visible blank `[[BLANK: name, what is needed]]` that is also
listed in `unfilled_placeholders`. Party names, licence numbers, addresses of parties and
legal descriptions have no binding at all, so they can only come from `fields` (legal.md 1.1).
"""
from __future__ import annotations

import re
from dataclasses import dataclass, field
from pathlib import Path
from typing import Callable, Literal, Mapping, Optional

from backend.schema import (DocType, DocumentDraft, DocumentRequest, PropertyBundle, RunResult,
                            Segment)

STATE_NAMES = {"CA": "California", "TX": "Texas"}
DISCLAIMER = ("DRAFT FOR ATTORNEY REVIEW. NOT LEGAL ADVICE. This document was generated by "
              "software from an energy analysis and has not been reviewed by a lawyer. Do not "
              "sign it until a lawyer licensed in {state_name} has reviewed and completed it.")

_PLACEHOLDER = re.compile(r"\{\{\s*([a-z][a-z0-9_]*)\s*\}\}")
_HEADER = re.compile(r"<!--\s*(doc|optional|segments):\s*(.*?)\s*-->")


@dataclass
class Context:
    request: DocumentRequest
    run: RunResult
    bundle: Optional[PropertyBundle] = None

    def field(self, name: str) -> Optional[str]:
        v = self.request.fields.get(name)
        return v if v not in (None, "") else None


Binding = Callable[[Context], Optional[str]]


@dataclass
class Template:
    doc_type: DocType
    state: Literal["CA", "TX"]
    body: str
    version: str = "v0.1"
    optional: frozenset[str] = frozenset()
    segments: tuple[str, ...] = ("residential", "commercial")


# ---------- derived bindings (the only placeholders the engine may fill itself) ----------

def _role_text(c: Context) -> str:
    return "tenant" if c.run.request.role == "tenant" else "owner"


def _cancel_title(c: Context) -> Optional[str]:
    senior = (c.field("buyer_is_senior") or "").lower()
    return {"yes": "Five-Day Right to Cancel", "no": "Three-Day Right to Cancel"}.get(senior)


DEFAULT_BINDINGS: dict[str, Binding] = {
    "state_name": lambda c: STATE_NAMES[c.request.state],
    "disclaimer": lambda c: DISCLAIMER.format(state_name=STATE_NAMES[c.request.state]),
    "owner_role_text": _role_text,
    "property_address": lambda c: c.run.property.address,
    "property_city": lambda c: c.run.property.city,
    "cancel_title": _cancel_title,
}

_NEEDS = {"stat_": "insert verbatim statutory text"}


def _blank(name: str, needs: Mapping[str, str]) -> str:
    what = needs.get(name) or next((v for p, v in _NEEDS.items() if name.startswith(p)),
                                   "value required")
    return f"[[BLANK: {name}, {what}]]"


# ---------- template loading ----------

def load_template(text: str) -> Template:
    """Parse the header comments of a template file:
    `<!-- doc: <doc_type> / <state> / template <version> -->`, optional
    `<!-- optional: name, name -->` and `<!-- segments: residential, commercial -->`."""
    meta: dict[str, str] = {}
    for key, value in _HEADER.findall(text):
        meta[key] = (meta[key] + ", " + value) if key in meta else value
    if "doc" not in meta:
        raise ValueError("template has no `<!-- doc: ... -->` header")
    parts = [p.strip() for p in meta["doc"].split("/")]
    if len(parts) < 2:
        raise ValueError(f"bad doc header: {meta['doc']!r}")
    version = parts[2].replace("template", "").strip() if len(parts) > 2 else "v0.1"
    return Template(
        doc_type=parts[0], state=parts[1], body=text, version=version or "v0.1",
        optional=frozenset(n.strip() for n in meta.get("optional", "").split(",") if n.strip()),
        segments=tuple(s.strip() for s in meta["segments"].split(",")) if "segments" in meta
        else ("residential", "commercial"))


def load_templates(directory: Path) -> dict[tuple[str, str], Template]:
    out: dict[tuple[str, str], Template] = {}
    for p in sorted(Path(directory).rglob("*.md")):
        t = load_template(p.read_text())
        out[(t.doc_type, t.state)] = t
    return out


def placeholders_in(text: str) -> list[str]:
    seen: list[str] = []
    for n in _PLACEHOLDER.findall(text):
        if n not in seen:
            seen.append(n)
    return seen


# ---------- the door-facing functions ----------

def list_templates(registry: Mapping[tuple[str, str], Template],
                   state: Optional[str] = None, segment: Optional[Segment] = None) -> list[DocType]:
    out: list[DocType] = []
    for (doc_type, st), t in registry.items():
        if state and st != state:
            continue
        if segment and segment not in t.segments:
            continue
        if doc_type not in out:
            out.append(doc_type)
    return out


def fill_template(request: DocumentRequest, run: RunResult,
                  bundle: Optional[PropertyBundle], template: Template,
                  statutory: Optional[Mapping[str, str]] = None,
                  bindings: Optional[Mapping[str, Binding]] = None,
                  needs: Optional[Mapping[str, str]] = None) -> DocumentDraft:
    """Fill one template. `statutory` maps `stat_` names to verbatim text from the state file;
    `needs` maps a placeholder to the words shown inside its blank."""
    if (template.doc_type, template.state) != (request.doc_type, request.state):
        raise ValueError("template does not match the request's doc_type and state")
    ctx = Context(request, run, bundle)
    binds = {**DEFAULT_BINDINGS, **(bindings or {})}
    statutory = statutory or {}
    needs = needs or {}
    unfilled: list[str] = []

    def resolve(match: re.Match) -> str:
        name = match.group(1)
        value = ctx.field(name)
        if value is None and name in binds:
            value = binds[name](ctx)
        if value is None and name.startswith("stat_"):
            value = statutory.get(name)
        if value is not None:
            return str(value)
        if name in template.optional:
            return ""
        if name not in unfilled:
            unfilled.append(name)
        return _blank(name, needs)

    markdown = _PLACEHOLDER.sub(resolve, template.body)
    notice = DISCLAIMER.format(state_name=STATE_NAMES[template.state])
    if "{{disclaimer}}" not in template.body:        # the notice is always present, top and bottom
        markdown = f"> {notice}\n\n{markdown.rstrip()}\n\n> {notice}\n"
    return DocumentDraft(
        doc_id=f"doc_{request.run_id}_{request.doc_type}_{request.state}",
        doc_type=request.doc_type, state=request.state, markdown=markdown,
        unfilled_placeholders=unfilled, statutory_checks=[], disclaimer=notice)
